"""Render existing results; no model fitting, simulation, or data fetching."""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
from pathlib import Path

import pymupdf as pdf

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "generated"
OUT.mkdir(exist_ok=True)
INPUTS: dict[str, str] = {}


def read(path: str) -> str:
    p = ROOT / path
    raw = p.read_bytes()
    INPUTS[path] = hashlib.sha256(raw).hexdigest()
    return raw.decode()


def result(n: str) -> dict:
    return json.loads(read(f"experiments/{n}/results.json"))


def pct(x: float) -> str:
    return f"{100*x:.1f}"


def rows(name: str, data: list[list[str]]) -> None:
    (OUT / f"{name}.tex").write_text("% Generated by prepare.py; edit source selection there.\n" +
        "\n".join(" & ".join(row) + r" \\" for row in data) + "\n")


def tex(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


INK = (0.14, 0.24, 0.32)
BLUE = (0.21, 0.43, 0.57)
RUST = (0.68, 0.36, 0.21)
GRAY = (0.43, 0.47, 0.49)
LIGHT = (0.87, 0.89, 0.90)


def chart(name: str, labels: list[str], series: list[tuple[str, list[float], tuple]],
          xmax: float, note: str) -> None:
    """Small horizontal comparisons as vector PDFs, keeping all text selectable."""
    height = 76 + 49 * len(labels)
    doc = pdf.open()
    page = doc.new_page(width=520, height=height)
    x0, x1 = 170, 478
    for i in range(5):
        x = x0 + (x1-x0) * i / 4
        page.draw_line((x, 33), (x, height-39), color=LIGHT, width=0.5)
        page.insert_text((x-7, height-24), f"{xmax*i/4:.0f}", fontsize=9, color=GRAY)
    lx = 10
    for title, _, color in series:
        page.draw_rect(pdf.Rect(lx, 7, lx+9, 16), color=color, fill=color)
        page.insert_text((lx+14, 15), title, fontsize=9, color=INK)
        lx += 170
    for i, label in enumerate(labels):
        y = 43 + i * 49
        page.insert_textbox(pdf.Rect(8, y, 160, y+35), label, fontsize=10, color=INK)
        for j, (_, values, color) in enumerate(series):
            v = 100*values[i]
            yy = y + j*13
            x = x0 + (x1-x0)*v/xmax
            if v > 0:
                page.draw_rect(pdf.Rect(x0, yy, x, yy+8), color=color, fill=color)
            page.insert_text((x+4, yy+8), f"{v:.1f}", fontsize=8, color=INK)
    page.insert_text((x0, height-9), note, fontsize=8, color=GRAY)
    doc.set_metadata({"title": name, "producer": "manuscript/prepare.py (PyMuPDF)"})
    doc.save(OUT / f"{name}.pdf", garbage=4, deflate=True, no_new_id=True)
    doc.close()


def main() -> None:
    d40, d54, d55, d56 = (result(n) for n in ("040", "054", "055", "056"))
    data = []
    for key, label in [("daily|full", "Daily, full record"), ("daily|to_peak", "Daily, to peak"),
                       ("hourly|full", "Hourly")]:
        a = d40["results"][key]["0.05"]
        ci = a["heldout_size_ci95"]
        data.append([label, pct(a["calm_nominal_rate"]), pct(a["heldout_size"]),
                     f"{pct(ci[0])}--{pct(ci[1])}", pct(a["separation"]["positive"]["flag_rate_empirical"])])
    rows("calibration", data)
    rows("daily_periods", [[tex(k), f"{a['all']['n']:,}", pct(a['all']['batch']),
                            pct(a['all']['monitor']), pct(a['all']['gsadf']), pct(a['calm']['batch'])]
                           for k, a in d56["universe"]["periods"].items()])
    sim = [("I61", r"Market scale, $\nu=6,\beta=1$"), ("I62", r"Market scale, $\nu=6,\beta=2$"),
           ("I101", r"Market scale, $\nu=10,\beta=1$"), ("I102", r"Market scale, $\nu=10,\beta=2$"),
           ("P1", r"Persistent effect, $\beta=1$"), ("CV_p2.0", r"Constant-volatility CEV, $p=2$"),
           ("SVa_r+0.0_p2.0", r"Market-driven SV, $p=2,\rho=0$"),
           ("SVb_r+0.0_p2.0", r"Own-stock SV, $p=2,\rho=0$")]
    rows("simulation", [[label] + [pct(d55['cells'][key]['matched'][m]['rate']) for m in
                                    ['fitted|batch', 'fitted|monitor', 'g0|batch', 'gsadf']]
                         for key, label in sim])
    names = {"DHI": "D.R. Horton", "LEN": "Lennar", "PHM": "Pulte", "TOL": "Toll Brothers"}
    homes = [r for r in d56['episodes'] if r['set'] == '021' and r['row'] == 'E3' and r['name'] in names]
    homes.sort(key=lambda r: list(names).index(r['name']))
    rows("homebuilders", [[names[r['name']], r['monitor_first_alarm'], r['peak'],
                           str(-r['monitor_sessions_from_peak']),
                           str(-r['gsadf_sessions_from_peak']) if r['gsadf_sessions_from_peak'] is not None else '---']
                          for r in homes])
    transport = [("I60", "Reference family"), ("SVa_r+0.0_p1.0", "Market SV, zero correlation"),
                 ("SVb_r+0.0_p1.0", "Own SV, zero correlation"),
                 ("SVb_r+0.7_p1.0", "Own SV, positive correlation")]
    # The reference's own matched threshold is also its transported threshold.
    tr = lambda k: d55['cells'][k].get('transported', d55['cells'][k]['matched'])
    rows("transport", [[label, pct(d55['cells'][key]['matched']['fitted|monitor']['rate']),
                         pct(tr(key)['fitted|monitor']['rate'])] for key, label in transport])
    chart("calibration_transport", [x[1] for x in transport],
          [("Matched calibration", [d55['cells'][k]['matched']['fitted|monitor']['rate'] for k, _ in transport], BLUE),
           ("Reference-family cutoff", [tr(k)['fitted|monitor']['rate'] for k, _ in transport], RUST)],
          80, "Monitor flag rate (%) in simulation; 500 evaluation paths per cell")
    p = d56['universe']['periods']
    chart("daily_flags", list(p),
          [("Daily market-scale monitor", [a['all']['monitor'] for a in p.values()], BLUE),
           ("Calibrated GSADF", [a['all']['gsadf'] for a in p.values()], RUST)],
          20, "Real-data launch flag rate (%); these are not false-alarm rates")
    ir = []
    for k, label in [('all','All run-up launches'), ('E5','Meme stocks, 2020--21'),
                     ('E9','Growth names'), ('033-B','Narrative names, 2023--26')]:
        a = d54['positive_launches'][k]
        ir.append([label, str(a['launches']), pct(a['monitor_alarm_share']), pct(a['gsadf_alarm_share'])])
    for k,label in [('members','Same-date calm members'), ('SPY/DIA','Same-date SPY and DIA')]:
        a=d54['controls'][k]
        ir.append([label, str(a['launches']), pct(a['monitor_alarm_share']), pct(a['gsadf_alarm_share'])])
    rows("intraday", ir)
    rows("forecast", [[str(h)] + [f"{100*d54['forward']['full'][f'mdd{h}|{m}']['oos_r2']:.2f}" for m in
                                  ['monitor','gsadf','monitor+gsadf']] for h in [63,126]])
    # Small path diagram: explicitly illustrative, not a simulated or observed record.
    doc=pdf.open(); pg=doc.new_page(width=520,height=185)
    points=[(45,52),(115,52),(185,139),(255,52),(325,52),(395,52),(465,52)]
    pg.draw_polyline(points,color=BLUE,width=2)
    pg.draw_line((45,110),(465,110),color=RUST,width=1,dashes='[5 3]')
    for x in [45,115,255,325,395,465]: pg.draw_circle((x,52),3,color=INK,fill=INK)
    pg.insert_text((47,32),'Observed underlying prices',fontsize=11,color=INK)
    pg.insert_text((290,105),'Liquidation boundary',fontsize=10,color=RUST)
    pg.insert_text((110,162),'An unobserved breach changes the contract outcome.',fontsize=10,color=INK)
    pg.insert_text((46,179),'Schematic only; dots are observation times.',fontsize=9,color=GRAY)
    doc.save(OUT/'missed_liquidation.pdf',garbage=4,deflate=True,no_new_id=True); doc.close()
    # Bibliography entries are built from the same registry as paper/build.
    texts='\n'.join(p.read_text() for p in [HERE/'main.tex', *sorted((HERE/'sections').glob('*.tex'))])
    keys=set()
    for group in re.findall(r'\\cite(?:[pt])?(?:\[[^]]*\])?\{([^}]+)\}',texts):
        keys.update(x.strip() for x in group.split(','))
    registry={}
    for line in read('refs/BIBLIOGRAPHY.md').splitlines():
        if line.startswith('| `'):
            c=[x.strip() for x in line.strip().strip('|').split('|')]
            registry[c[0].strip('`')]=c
    missing=keys-registry.keys()
    if missing: raise ValueError(f'Unknown bibliography keys: {sorted(missing)}')
    editions=json.loads(read('manuscript/sources/bibliography.json'))
    for k in editions:
        p=HERE/'sources'/f'{k}.pdf'
        INPUTS[str(p.relative_to(ROOT))]=hashlib.sha256(p.read_bytes()).hexdigest()
    bib=[]
    for k in sorted(keys):
        c=registry[k]
        m=re.match(r'(.*?)\s*\((\d{4})[^)]*\)\.\s*(.*?[.?!])\s+(.*)$',c[1]) or \
          re.match(r'(.*?)\s*\((\d{4})[^)]*\)\.\s*(.*?[.?!])\s*()$',c[1])
        if not m: raise ValueError(f'Cannot parse citation {k}: {c[1]}')
        au,yr,ti,venue=m.groups()
        author=' and '.join(dict.fromkeys(x.strip() for x in au.split(',') if x.strip()))
        doi=c[2]
        doi_line=f'  doi = {{{doi}}},\n' if doi.startswith('10.') else ''
        url = c[3].split()[0].rstrip(';,.')
        if not url.startswith(('http://', 'https://')):
            url = f'https://doi.org/{doi}' if doi.startswith('10.') else ''
        if k in editions:
            edition=editions[k]
            author,yr,ti,venue=(edition[field] for field in ('author','year','title','howpublished'))
            doi=edition.get('doi','')
            doi_line=f'  doi = {{{doi}}},\n' if doi else ''
            url=edition['url']
        url_line = f'  url = {{{url}}},\n' if url else ''
        bib.append(f'@misc{{{k},\n  author = {{{tex(author)}}},\n  title = {{{{{tex(ti.rstrip("."))}}}}},\n'
                   f'  year = {{{yr}}},\n  howpublished = {{{tex(venue)}}},\n{doi_line}{url_line}'
                   '}')
    (OUT/'references.bib').write_text('\n\n'.join(bib)+'\n')
    rev=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    (OUT/'provenance.json').write_text(json.dumps({'research_revision':rev,'inputs_sha256':INPUTS,
        'bibliography_keys':sorted(keys),'note':'Existing results only; no experiment rerun.'},indent=2)+'\n')
    print(f'Prepared 7 tables, 3 vector figures, and {len(keys)} bibliography entries.')


if __name__ == '__main__':
    main()
